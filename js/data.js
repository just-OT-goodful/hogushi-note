export function doseText(ex) {
  const d = ex.dose;
  if (d.type === 'hold') {
    const side = d.sides === 2 ? '左右' : '';
    return `${d.sec}秒キープ × ${side ? side + ' × ' : ''}${d.sets}セット`.replace(' × 1セット', '');
  }
  const hold = d.hold ? `（${d.hold}秒キープ）` : '';
  return `${d.reps}回${hold}${d.sets > 1 ? ` × ${d.sets}セット` : ''}`;
}

